"""Alembic environment. Uses the app's engine settings and model metadata."""
from alembic import context

from app.database import Base, engine
import app.models  # noqa: F401  (registers every table on Base.metadata)

config = context.config
target_metadata = Base.metadata


def run_migrations_offline():
    context.configure(url=str(engine.url), target_metadata=target_metadata,
                      literal_binds=True, render_as_batch=True)
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online():
    connection = config.attributes.get("connection")
    if connection is not None:
        _run(connection)
        return
    with engine.begin() as connection:
        _run(connection)


def _run(connection):
    # render_as_batch lets autogenerated revisions alter columns on SQLite.
    context.configure(connection=connection, target_metadata=target_metadata, render_as_batch=True)
    with context.begin_transaction():
        context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
